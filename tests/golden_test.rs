//! Golden-PDF regression tests (M6, P1).
//!
//! Strategy — two layers:
//!   1. **Determinism**: rendering the same input twice MUST produce
//!      byte-identical output (SHA-256). M3 verified this property for
//!      CJK docs; this test locks it in for the whole corpus.
//!   2. **Page-count baseline**: page counts are stable across machines
//!      (fonts embed differently per platform, so byte-level hashes are
//!      NOT portable — page structure is). Baseline stored in
//!      `tests/golden/baseline.json`; regenerate with
//!      `UPDATE_GOLDEN=1 cargo test --test golden_test`.
//!
//! Corpus covers the feature surface most likely to regress silently:
//! CJK (searchable text layer), GBK rare chars, math, tables, code
//! highlighting, mixed long-form content.

