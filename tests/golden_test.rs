fn golden_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/golden")
}

fn baseline_path() -> PathBuf {
    golden_dir().join("baseline.json")
}

/// Render markdown via the library API (no CLI, no font flags — same as CI).
/// Returns the PDF bytes.
fn render(md: &str) -> Vec<u8> {
    let dir = tempfile::tempdir().expect("temp dir");
    let out = dir.path().join("out.pdf");
    typepress::render_markdown_to_pdf(md, &out, &[], &[], None, None)
        .unwrap_or_else(|e| panic!("render failed: {e}"));
    std::fs::read(&out).expect("read rendered pdf")
}

fn sha256(bytes: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(bytes);
    format!("{:x}", h.finalize())
}

#[test]
fn golden_determinism() {
    // Same input twice → byte-identical output. This is the core
    // industrial-grade property: reproducible builds.
    for (name, md) in corpus() {
        let pdf1 = render(md);
        let pdf2 = render(md);
        assert!(!pdf1.is_empty(), "{name}: empty PDF");
        assert_eq!(
            sha256(&pdf1),
            sha256(&pdf2),
            "{name}: non-deterministic output (two renders differ)"
        );
        // Sanity: real PDF header + at least one page.
        assert!(pdf1.starts_with(b"%PDF"), "{name}: not a PDF");
        assert!(crate_page_count(&pdf1) >= 1, "{name}: no pages");
    }
}

#[test]
fn golden_page_count_baseline() {
    // Page counts must match the committed baseline (stable across
    // platforms even though font embedding differs).
    if !baseline_path().exists() {
        if std::env::var("UPDATE_GOLDEN").is_ok() {
            eprintln!("SKIP: baseline regenerated by sibling test (UPDATE_GOLDEN=1)");
            return;
        }
        panic!("baseline.json missing — run UPDATE_GOLDEN=1 cargo test --test golden_test");
    }
    let baseline: std::collections::BTreeMap<String, usize> =
        serde_json::from_str(&std::fs::read_to_string(baseline_path()).expect("baseline.json"))
            .expect("parse baseline");
    assert_eq!(
        baseline.len(),
        corpus().len(),
        "baseline.json out of sync — run UPDATE_GOLDEN=1"
    );
    for (name, md) in corpus() {
        let pdf = render(md);
        let pages = crate_page_count(&pdf);
        let expected = baseline
            .get(name)
            .unwrap_or_else(|| panic!("{name}: missing from baseline"));
        assert_eq!(
            &pages, expected,
            "{name}: page count changed ({pages} != {expected}) — intentional layout change? run UPDATE_GOLDEN=1"
        );
    }
}

/// Count pages by counting /Type /Page objects (regex over raw bytes).
fn crate_page_count(pdf: &[u8]) -> usize {
    let text = String::from_utf8_lossy(pdf);
    let re = regex::Regex::new(r"/Type\s*/Page[^s]").unwrap();
    re.find_iter(&text).count()
}

/// Regenerate baseline.json from the current renderer output.
/// Driven by UPDATE_GOLDEN=1 so CI never rewrites files.
#[test]
fn golden_regenerate_when_flagged() {
    if std::env::var("UPDATE_GOLDEN").is_ok() {
        let mut map = std::collections::BTreeMap::new();
        for (name, md) in corpus() {
            let pdf = render(md);
            map.insert(name.to_string(), crate_page_count(&pdf));
        }
        let json = serde_json::to_string_pretty(&map).unwrap();
        std::fs::create_dir_all(golden_dir()).expect("create golden dir");
        std::fs::write(baseline_path(), json).expect("write baseline.json");
        eprintln!(
            "golden baseline regenerated -> {}",
            baseline_path().display()
        );
    }
}
